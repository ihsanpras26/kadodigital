export function getThemePreviewMeta(theme: ThemeItem): ThemePreviewMeta {
  return (
    SLUG_PREVIEW_META[theme.slug] ?? {
      coverSrc: "/themes/catalog-covers/event-party.jpg",
      topTag: `${theme.subCategory} · RSVP`,
      kicker: theme.subCategory,
      headline: theme.name,
      meta: "Pratinjau Interaktif",
      ctaLabel: theme.line === "kado-personal" ? "Buka Kado Sekarang" : "Buka Undangan",
      bottomHint: theme.mechanics.slice(0, 2).join(" · "),
    }
  );
}
